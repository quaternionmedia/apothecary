"""A part's SCAD edited from the browser: drafts checked and rendered.

The second and third iterations of
docs/plans/part-editing-in-the-browser-2026-09-27.md, server side. A draft is
the part's SCAD as the page holds it, sent whole with each request; nothing is
kept between requests but what the variant cache keeps.

- ``POST /parts/{name}/draft/check`` ``{scad, params}``: the draft evaluated
  and not rendered (apothecary/projects/parts/drafts.py) -- what OpenSCAD said
  of it by line, naming the part's SCAD; the fields an editor builds its
  controls from (the part's model's, or, for a part without one, what the
  draft itself declares where OpenSCAD lists it); and the staged ``params``
  checked against them. What a page asks once typing pauses.
- ``POST /parts/{name}/draft/render`` ``{scad, params}``: the draft rendered
  into the variant cache, answered as ``POST /parts/{name}/stl/generate``
  answers (``draft`` naming the text), errors by line in a 422 as Apply's are.
  A newer request from the same ``page`` stops this one's OpenSCAD run (409),
  an Apply's included. A draft the same as the part's SCAD is the part.
- ``GET /parts/{name}/variants/{key}/scad``: the draft a cached variant was
  rendered from, for a tab reloaded on it.

A part whose geometry is Python (the snowplow) is read-only: its SCAD is the
one its geometry generates (``GET /parts/{name}/scad``), and a draft of it is
a 403.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

from fastapi import APIRouter, HTTPException, Query
from fastapi.responses import PlainTextResponse
from pydantic import BaseModel, Field

from ..projects.parts.base import BasePart
from ..projects.parts.customizer import INSTALL_HINT, lists_parameters, scad_fields
from ..projects.parts.drafts import (
    DRAFT_LIMIT,
    ReadOnly,
    check_draft,
    draft_digest,
    refuse_read_only,
)
from ..projects.parts.openscad_messages import OpenSCADMessage
from ..projects.parts.params import (
    FROM_CUSTOMIZER,
    FROM_MODEL,
    FieldError,
    ParamField,
    params_spec,
    validate_staged,
)
from ..projects.parts.stl_renderer import get_renderer, part_renderer
from ..projects.parts.variants import make_variant, read_variant_draft, same_text
from ..projects.parts.variants import wants as request_wants

router = APIRouter(tags=["parts"])

PAGE = Query(
    None,
    max_length=128,
    description="An id the page makes up once per load. A newer request from the same page "
    "for the same part stops this one's OpenSCAD run (409).",
)


def _api():
    from .. import api

    return api


def _editable(name: str) -> BasePart:
    """The part, or a 403 for one whose SCAD is generated by its Python geometry."""
    part = _api()._load_part_wrapper(name)
    try:
        refuse_read_only(part)
    except ReadOnly as exc:
        raise HTTPException(status_code=403, detail=str(exc)) from None
    return part


def _openscad_or_503() -> None:
    if not get_renderer().is_available:
        raise HTTPException(
            status_code=503, detail="OpenSCAD not installed. Cannot check or render."
        )


class DraftRequest(BaseModel):
    """A part's SCAD as the page holds it, and the parameters staged on it."""

    scad: str = Field(..., max_length=DRAFT_LIMIT, description="The whole SCAD, as edited")
    params: Dict[str, Any] = Field(
        default_factory=dict, description="Parameter values staged in the editor's controls"
    )


class DraftCheck(BaseModel):
    """A draft evaluated, not rendered, and its staged parameters checked."""

    part: str
    draft: str = Field(description="The sha256 of the text checked")
    edited: bool = Field(description="It differs from the part's SCAD on disk")
    valid: bool = Field(
        description="OpenSCAD evaluated it without an error, and the staged parameters are valid"
    )
    checked_by: str = Field(
        description='"param": the customizer\'s export, which lists parameters; '
        '"echo": the echo export (2021.01), which only evaluates'
    )
    openscad: Optional[str] = None
    listed: bool = Field(description="OpenSCAD listed the parameters the draft declares")
    messages: List[OpenSCADMessage] = Field(default_factory=list)
    source: Optional[str] = Field(
        None, description='Where ``fields`` come from: "model" or "customizer"; None for none'
    )
    fields: List[ParamField] = Field(default_factory=list)
    params: Dict[str, Any] = Field(default_factory=dict)
    errors: List[FieldError] = Field(default_factory=list)
    note: Optional[str] = Field(None, description="What could not be done, and why")


@router.post("/parts/{name}/draft/check", response_model=DraftCheck)
def check_part_draft(name: str, body: DraftRequest, page: Optional[str] = PAGE):
    """A draft of the part's SCAD, evaluated by OpenSCAD and not rendered.

    The draft is written beside the part for the one run, so its includes
    resolve, and removed after. ``messages`` are what OpenSCAD said, by line
    of the draft (they name the part's SCAD). ``fields`` are what an editor
    builds its controls from: the part's model's, or, for a part without one,
    the parameters the draft declares, where the OpenSCAD lists them
    (``listed``; 2021.01 cannot, and ``note`` says so). ``params`` are checked
    against them. A newer check from the same ``page`` stops this one (409).
    A part built by Python geometry is a 403: its SCAD is generated."""
    api = _api()
    part = _editable(name)
    _openscad_or_503()
    renderer = part_renderer(part)
    digest = draft_digest(body.scad)
    slot = f"{page}#check" if page else None
    cancel = api._page_renders.begin(part.name, slot, digest)
    try:
        check = check_draft(part, body.scad, renderer, cancel)
    finally:
        api._page_renders.end(part.name, slot, cancel)
    if check.cancelled:
        raise HTTPException(
            status_code=409, detail={"message": check.error_message, "superseded": True}
        )

    note = None
    if part.params_model is not None:
        fields, source = params_spec(part).fields, FROM_MODEL
        staged = validate_staged(part, body.params)
    else:
        listing = check.parameters
        fields = scad_fields(listing) if listing else []
        source = FROM_CUSTOMIZER if listing else None
        staged = api.validate_without_model(part, body.params, listing, scad_text=body.scad)
        if not check.lists:
            note = f"{check.openscad} cannot list the draft's parameters ({INSTALL_HINT})"
    if check.error_message:
        note = check.error_message if note is None else f"{check.error_message}; {note}"
    said_error = any(m.level == "error" for m in check.messages)
    return DraftCheck(
        part=part.name,
        draft=digest,
        edited=not same_text(part.source_file, body.scad),
        valid=check.ok and not said_error and staged.valid,
        checked_by=check.how,
        openscad=check.openscad,
        listed=check.parameters is not None,
        messages=check.messages,
        source=source,
        fields=fields,
        params=staged.params,
        errors=staged.errors,
        note=note,
    )


@router.post("/parts/{name}/draft/render")
def render_part_draft(
    name: str,
    body: DraftRequest,
    force: bool = Query(False, description="Render even what the cache already has"),
    page: Optional[str] = PAGE,
):
    """A draft of the part's SCAD rendered into the variant cache, with ``params``.

    Answered as ``POST /parts/{name}/stl/generate`` answers, ``draft`` the
    sha256 of the text (None when it is the part's SCAD as it is on disk, which
    is then the part). The draft is written beside the part for the one run;
    the part's own SCAD and STL are never touched. ``params`` are checked
    against the part's model, or what the draft declares (422). OpenSCAD's
    errors come back by line in a 422, as Apply's do; a newer request from
    the same ``page`` stops this one (409). A part built by Python geometry is
    a 403."""
    api = _api()
    part = _editable(name)
    _openscad_or_503()
    renderer = part_renderer(part)
    listing = None
    if part.params_model is None and lists_parameters(renderer.openscad_path):
        listing = check_draft(part, body.scad, renderer).parameters
    overrides = api.checked_overrides(part, body.params, listing, scad_text=body.scad)
    wants = f"{request_wants(overrides, force)}\0{draft_digest(body.scad)}"
    cancel = api._page_renders.begin(part.name, page, wants)
    try:
        made = make_variant(part, overrides, force=force, cancel=cancel, draft=body.scad)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from None
    finally:
        api._page_renders.end(part.name, page, cancel)
    return api.made_answer(name, part, made, overrides)


@router.get("/parts/{name}/variants/{variant}/scad", response_class=PlainTextResponse)
def get_variant_draft(name: str, variant: str):
    """The draft a cached variant was rendered from: what a tab reloaded on that
    variant shows in its editor. 404 for a variant of the part's own SCAD
    (``GET /parts/{name}/scad`` is that), or one the cache has let go."""
    part = _api()._load_part_wrapper(name)
    text = read_variant_draft(part, variant)
    if text is None:
        raise HTTPException(
            status_code=404,
            detail=f"No draft is cached for variant '{variant}' of '{name}': a variant of the "
            f"part's own SCAD has none (GET /parts/{name}/scad), and the cache lets go of old ones",
        )
    return PlainTextResponse(text, headers={"X-Part-Variant": variant})


