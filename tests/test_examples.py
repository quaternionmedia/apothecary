"""Every example renders, and the lane for agents' own contributions keeps its word.

``examples/`` is small things to run, by kind (``examples/README.md``): scene documents, scripts
that build a scene, pictures, and ``llms_own/``, the lane for language-model agents' own
contributions. Each is held here: a document loads and renders, a script runs and prints
OpenSCAD, a contribution has its README with its ``Tools:`` line and a JSON twin that is the
script's own output, and, with an OpenSCAD installed, each scene's SCAD compiles.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

from apothecary.example import create_example_scene
from apothecary.projects.parts.skeleton import ROOT
from apothecary.projects.parts.stl_renderer import get_renderer, run_openscad
from apothecary.scene import load_scene_from_json

EXAMPLES = ROOT / "examples"
SCENES = sorted((EXAMPLES / "scenes").glob("*.json"))
SCRIPTS = sorted((EXAMPLES / "scripts").glob("*.py"))
LANE = EXAMPLES / "llms_own"
CONTRIBUTIONS = sorted(p for p in LANE.iterdir() if p.is_dir() and not p.name.startswith("."))


def _run(script: Path, *args: str) -> str:
    done = subprocess.run(
        [sys.executable, str(script), *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert done.returncode == 0, done.stderr[-2000:]
    return done.stdout


def _compiles(scad: str, tmp_path: Path, name: str) -> None:
    """OpenSCAD compiles the SCAD to a CSG tree without an error (no CGAL, so quick)."""
    renderer = get_renderer()
    if not renderer.is_available:
        pytest.skip("OpenSCAD not installed")
    source = tmp_path / f"{name}.scad"
    source.write_text(scad, encoding="utf-8")
    code, _, err, stopped = run_openscad(
        renderer.openscad_path, ["-o", "-", "--export-format=csg", str(source)], tmp_path, 120
    )
    assert code == 0 and not stopped, err[-2000:]
    assert "ERROR" not in err, err[-2000:]


def test_the_index_names_every_kind():
    text = (EXAMPLES / "README.md").read_text(encoding="utf-8")
    for folder in ("scenes/", "scripts/", "pictures/", "llms_own/"):
        assert f"[{folder}]({folder})" in text, folder
    assert SCENES and SCRIPTS and CONTRIBUTIONS


@pytest.mark.parametrize("path", SCENES, ids=lambda p: p.name)
def test_a_scene_document_loads_and_renders(path, tmp_path):
    scene = load_scene_from_json(scene_file=path, allow_example_fallback=False)
    scad = scene.render()
    assert f"// Scene: {scene.name}" in scad
    _compiles(scad, tmp_path, path.stem)


def test_the_house_is_the_scene_render_falls_back_to():
    """``apothecary render`` with no scene renders ``create_example_scene()``; the file is it."""
    on_disk = json.loads((EXAMPLES / "scenes" / "house.json").read_text(encoding="utf-8"))
    built = create_example_scene().model_dump(mode="json", exclude_none=True, exclude={"version"})
    assert on_disk == {"name": built["name"], "objects": built["objects"]}


@pytest.mark.parametrize("script", SCRIPTS, ids=lambda p: p.name)
def test_a_script_prints_openscad(script, tmp_path):
    scad = _run(script)
    assert scad.startswith("// Generated by")
    _compiles(scad, tmp_path, script.stem)


def test_the_lane_has_its_charter():
    text = (LANE / "README.md").read_text(encoding="utf-8")
    assert text.startswith("# LLM's own")
    for word in ("README", "Tools:", "tests/test_examples.py", "parts/"):
        assert word in text, word


@pytest.mark.parametrize("folder", CONTRIBUTIONS, ids=lambda p: p.name)
def test_a_contribution_says_what_it_is_and_renders(folder, tmp_path):
    """One folder: a README in the present tense that ends with its Tools line, and a scene
    that renders -- a script, a document, or both; a JSON twin is the script's own output."""
    assert folder.name == folder.name.lower() and "-" not in folder.name, "underscores"
    readme = (folder / "README.md").read_text(encoding="utf-8")
    assert readme.startswith(f"# {folder.name}"), "the README is titled with the folder's name"
    assert readme.rstrip().splitlines()[-1].startswith("Tools:"), (
        "the README ends with its Tools line"
    )
    scripts = sorted(folder.glob("*.py"))
    documents = sorted(folder.glob("*.json"))
    assert scripts or documents, "a scene that renders"
    for script in scripts:
        scad = _run(script)
        assert scad.startswith("// Generated by")
        _compiles(scad, tmp_path, script.stem)
        twin = folder / f"{script.stem}.json"
        if twin.exists():
            assert json.loads(_run(script, "--json")) == json.loads(
                twin.read_text(encoding="utf-8")
            )
    for document in documents:
        scene = load_scene_from_json(scene_file=document, allow_example_fallback=False)
        assert scene.objects
