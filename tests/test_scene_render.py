from apothecary.example import create_example_scene


def test_example_scene_renders_header_and_objects():
    scene = create_example_scene()
    code = scene.render()
    assert code.startswith("// Generated by Apothecary v")
    assert code.endswith(";\n") or code.endswith("}\n")  # a file's worth: its last line ends
    assert "Scene: " in code
    assert "union()" in code or "difference()" in code
