def write_profiles(resources: Path) -> Path:
    """OrcaSlicer's ``resources/profiles`` as it ships them: the vendor's index, and
    each profile in its folder."""
    profiles = resources / "profiles"
    folder = profiles / "Creality"
    index = {"name": "Creality", "machine_list": [], "process_list": [], "filament_list": []}
    for kind, named in CREALITY.items():
        (folder / kind).mkdir(parents=True, exist_ok=True)
        for name, data in named.items():
            (folder / kind / f"{name}.json").write_text(json.dumps(data), encoding="utf-8")
            index[f"{kind}_list"].append({"name": name, "sub_path": f"{kind}/{name}.json"})
    (profiles / "Creality.json").write_text(json.dumps(index), encoding="utf-8")
    return profiles


def write_fake_orcaslicer(folder: Path) -> Path:
    """The fake at ``folder/bin/orca-slicer`` (this interpreter running it), its
    profiles at ``folder/resources`` -- where OrcaSlicer itself looks, one level up."""
    program = folder / "bin" / "orca-slicer"
    program.parent.mkdir(parents=True, exist_ok=True)
    program.write_text(
        FAKE_ORCASLICER.replace("#!/usr/bin/env python3", f"#!{sys.executable}", 1),
        encoding="utf-8",
    )
    program.chmod(program.stat().st_mode | stat.S_IXUSR)
    write_profiles(folder / "resources")
    return program


def fake_calls(program: Path) -> list[list[str]]:
    log = program.with_name(program.name + ".calls")
    if not log.exists():
        return []
    return [json.loads(line) for line in log.read_text().splitlines() if line.strip()]
